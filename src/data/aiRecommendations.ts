// 关键词匹配：去掉标点 + 小写 + 子串匹配
export function findBookInLibrary(input: string): { key: string; meta: BookMeta } | null {
  const normalized = input.replace(/[\s《》\u3000，。、！？：；·—\-]/g, '').toLowerCase()
  if (!normalized) return null
  // 1. 精确包含：输入是书名的子串
  for (const [key, meta] of Object.entries(bookLibrary)) {
    const k = key.toLowerCase()
    if (normalized.includes(k) || k.includes(normalized)) {
      return { key, meta }
    }
  }
  return null
}

// 把 BookMeta 转成 ReferenceAnchor（按当前画布维度）
export function bookToAnchor(bookKey: string, meta: BookMeta, dimension: string): ReferenceAnchor {
  const analysis = meta.byDimension[dimension]
  if (!analysis) {
    return {
      id: `b-${Date.now()}`,
      source: `${bookKey}（${meta.author}）`,
      features: `${meta.tags.join('、')} · 暂未提供「${dimension}」维度的具体分析`,
      examples: '（该书在当前维度的细化分析待补充）',
    }
  }
  return {
    id: `b-${Date.now()}`,
    source: `${bookKey}（${meta.author}）`,
    features: analysis.feature,
    examples: analysis.example,
  }
}

// 画布内容关键词匹配：content 包含某本书的 tag → 命中
export function findBookByContent(content: string): { key: string; meta: BookMeta } | null {
  const c = content.toLowerCase()
  if (!c.trim()) return null
  let best: { key: string; meta: BookMeta; score: number } | null = null
  for (const [key, meta] of Object.entries(bookLibrary)) {
    let score = 0
    for (const tag of meta.tags) {
      if (c.includes(tag.toLowerCase())) score += 1
    }
    if (score > 0 && (!best || score > best.score)) {
      best = { key, meta, score }
    }
  }
  return best ? { key: best.key, meta: best.meta } : null
}

