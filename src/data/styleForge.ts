/** 本地检测：找出描述里哪些词是空泛的（返回去重后的条目） */
export function detectEmptyWords(text: string): EmptyWord[] {
  if (!text.trim()) return []
  return EMPTY_WORDS.filter(e => text.includes(e.word))
}
