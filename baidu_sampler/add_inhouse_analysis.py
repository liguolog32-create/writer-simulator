def main():
    data = {}
    if OUT.exists():
        data = json.loads(OUT.read_text(encoding="utf-8"))

    DIMS = ["设定", "人物", "文笔", "结构", "篇幅", "情节", "节奏"]
    added, skipped = [], []
    for name, entry in ANALYSES.items():
        if name in data and "error" not in data[name]:
            skipped.append(name)
            continue
        missing = [d for d in DIMS if d not in entry.get("byDimension", {})]
        if missing:
            print(f"⚠️ {name} 缺维度 {missing}，跳过")
            continue
        data[name] = entry
        added.append(name)

    OUT.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"✅ 新增 {len(added)} 本: {added}")
    if skipped:
        print(f"⏭ 已存在跳过: {skipped}")
    print(f"📚 语料库现有 {len([k for k,v in data.items() if 'error' not in v])} 本")


if __name__ == "__main__":
    main()
